export function getProductBySlugOrId(identifier: string): Product | undefined {
  // Support canonical Meta Ad aliases
  const normalized = identifier.toLowerCase().trim();
  if (normalized === 'elegant-earrings') {
    return PRODUCTS.find((p) => p.slug === 'aurora-pearl-drop-earrings');
  }
  if (normalized === 'pendant-necklace') {
    return PRODUCTS.find((p) => p.slug === 'celestial-solitaire-pendant');
  }
  if (normalized === 'traditional-bangles') {
    return PRODUCTS.find((p) => p.slug === 'royal-filigree-heritage-bangles');
  }

  return PRODUCTS.find(
    (p) => p.slug === identifier || p.id === identifier
  );
}

// Format INR currency accurately
export function formatINR(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}
